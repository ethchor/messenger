#!/usr/bin/env python3
"""Writes the emoji picker's list for both apps from emojibase-data (MIT).

    npm pack emojibase-data@17.0.0 && tar -xzf emojibase-data-17.0.0.tgz
    scripts/emoji.py package/en/data.json

The list is plain text, one emoji per line under "@" group headings:

    @Smileys & emotion
    😀<tab>grinning face<tab>face grin grinning
    👋<tab>waving hand<tab>hand wave waving<tab>👋🏻 👋🏼 👋🏽 👋🏾 👋🏿

The fourth field, when there is one, is the five skin tones, light to dark.
Only emoji up to Unicode Emoji 15.0 are kept: iPhone (iOS 17) and Android
14 draw those, so nobody gets a reaction they see as a blank box.
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUTS = [
    ROOT / "apple" / "Messenger" / "Resources" / "emoji.tsv",
    ROOT / "android" / "app" / "src" / "main" / "assets" / "emoji.tsv",
]
SOURCE = "emojibase-data 17.0.0"
NEWEST = 15.0
# emojibase's groups, in its order. 2 (skin tone and hair parts) isn't offered.
GROUPS = {
    0: "Smileys & emotion",
    1: "People & body",
    3: "Animals & nature",
    4: "Food & drink",
    5: "Travel & places",
    6: "Activities",
    7: "Objects",
    8: "Symbols",
    9: "Flags",
}


def plain(emoji):
    """One pictograph from outside the Basic Multilingual Plane needs no
    emoji variation selector; the core drops it from reactions too, so 👍
    from the picker and 👍 from a quick reaction are the same reaction."""
    if len(emoji) == 2 and emoji[1] == "\ufe0f" and ord(emoji[0]) >= 0x1F000:
        return emoji[0]
    return emoji


def clean(text):
    return " ".join(text.replace("\t", " ").split())


def tones(entry):
    """The five same-tone variants, light to dark, or None."""
    by_tone = {}
    for skin in entry.get("skins", []):
        tone = skin.get("tone")
        if isinstance(tone, list):
            if len(set(tone)) != 1:
                continue
            tone = tone[0]
        if skin.get("version", 0) <= NEWEST:
            by_tone[tone] = skin["emoji"]
    return [by_tone[t] for t in range(1, 6)] if all(t in by_tone for t in range(1, 6)) else None


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = json.loads(pathlib.Path(sys.argv[1]).read_text())
    lines = [f"# Generated by scripts/emoji.py from {SOURCE} (MIT). Don't edit; run the script."]
    count = 0
    for group, title in GROUPS.items():
        entries = sorted(
            (e for e in data if e.get("group") == group and e.get("version", 99) <= NEWEST),
            key=lambda e: e.get("order", 0),
        )
        lines.append(f"@{title}")
        for e in entries:
            label = clean(e["label"])
            words = clean(" ".join(e.get("tags", [])))
            fields = [plain(e["emoji"]), label, words]
            variants = tones(e)
            if variants:
                fields.append(" ".join(variants))
            lines.append("\t".join(fields))
            count += 1
    text = "\n".join(lines) + "\n"
    for path in OUTPUTS:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"{count} emoji")


if __name__ == "__main__":
    main()
