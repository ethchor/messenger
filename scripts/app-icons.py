#!/usr/bin/env python3
"""Draws the app icons from design/artwork/mark.svg: the speech bubble that is
also a padlock, in paper white on the blue-black ink.

    scripts/app-icons.py

Writes the iPhone and Mac icons (PNG, in the asset catalog), and Android's
adaptive launcher icon and status bar icon (vector drawables). Needs
`pip install svgelements cairosvg pillow`.
"""

import io
import pathlib
import sys

import cairosvg
from PIL import Image, ImageFilter

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from artwork import load, number  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
MARK = load(ROOT / "design" / "artwork" / "mark.svg")
APPLE = ROOT / "apple" / "Messenger" / "Assets.xcassets" / "AppIcon.appiconset"
RES = ROOT / "android" / "app" / "src" / "main" / "res"

INK = "#26457E"  # blue-black, the default ink
PAPER = "#F6F7FA"
# Heavier than in the app, so the line holds up at small icon sizes.
ICON_STROKE = 3.3


def mark_svg(size, scale, offset, stroke, color, background=None, radius=0):
    """The mark at `scale` (pixels per drawing unit), moved by `offset`."""
    parts = []
    if background:
        inset, extent = background
        parts.append(
            f'<rect x="{inset}" y="{inset}" width="{extent}" height="{extent}" rx="{radius}" fill="{INK}"/>'
        )
    body = []
    for kind, data, line, dashes in MARK["strokes"]:
        if kind == "fill":
            body.append(f'<path d="{data}" fill="{color}" stroke="none"/>')
        else:
            body.append(f'<path d="{data}" fill="none" stroke="{color}" stroke-width="{stroke}"/>')
    parts.append(
        f'<g transform="translate({offset[0]} {offset[1]}) scale({scale})" stroke-linecap="round" '
        f'stroke-linejoin="round">{"".join(body)}</g>'
    )
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 {size} {size}">{"".join(parts)}</svg>'


def png(svg, size):
    return Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size)))


def centered(size, fraction):
    """Scale and offset that fit the mark's drawing box into `fraction` of `size`."""
    scale = size * fraction / MARK["height"]
    # The mark's lines sit a little low in their box: lift it to look centred.
    return scale, ((size - MARK["width"] * scale) / 2, (size - MARK["height"] * scale) / 2 - size * 0.01)


def iphone():
    scale, offset = centered(1024, 0.74)
    svg = mark_svg(1024, scale, offset, ICON_STROKE, PAPER, background=(0, 1024))
    png(svg, 1024).convert("RGB").save(APPLE / "icon-ios-1024.png")


def mac():
    # Apple's Mac grid: an 824-point rounded square in a 1024 canvas, with a soft shadow.
    canvas = 1024
    scale, offset = centered(824, 0.74)
    svg = mark_svg(canvas, scale, (offset[0] + 100, offset[1] + 100), ICON_STROKE, PAPER, background=(100, 824), radius=185)
    art = png(svg, canvas).convert("RGBA")
    shadow = Image.new("RGBA", (canvas, canvas), (0, 0, 0, 0))
    alpha = art.split()[3].point(lambda a: int(a * 0.32))
    shadow.paste((0, 0, 0, 255), (0, 12), alpha)
    shadow = shadow.filter(ImageFilter.GaussianBlur(16))
    icon = Image.alpha_composite(shadow, art)
    for points in (16, 32, 128, 256, 512):
        for factor in (1, 2):
            pixels = points * factor
            icon.resize((pixels, pixels), Image.LANCZOS).save(APPLE / f"icon-mac-{points}@{factor}x.png")


def vector(name, size_dp, viewport, scale, offset, stroke, color, comment):
    paths = []
    for kind, data, line, dashes in MARK["strokes"]:
        if kind == "fill":
            paths.append(f'        <path android:pathData="{data}" android:fillColor="{color}" />')
        else:
            paths.append(
                f'        <path android:pathData="{data}" android:fillColor="#00000000" android:strokeColor="{color}"\n'
                f'            android:strokeWidth="{number(stroke)}" android:strokeLineCap="round" android:strokeLineJoin="round" />'
            )
    xml = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {comment} Generated by scripts/app-icons.py. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
        f'    <group android:translateX="{number(offset[0])}" android:translateY="{number(offset[1])}"\n'
        f'        android:scaleX="{number(scale)}" android:scaleY="{number(scale)}">\n'
        + "\n".join(paths)
        + "\n    </group>\n</vector>\n"
    )
    (RES / "drawable" / f"{name}.xml").write_text(xml)


def android():
    # Adaptive icons are 108dp with the middle 66dp always visible.
    scale, offset = centered(108, 0.52)
    vector("ic_launcher_foreground", 108, 108, scale, offset, ICON_STROKE, PAPER, "Launcher icon: the mark.")
    vector("ic_launcher_monochrome", 108, 108, scale, offset, ICON_STROKE, "#FFFFFFFF", "Themed launcher icon.")
    scale, offset = centered(24, 0.92)
    vector("ic_notification", 24, 24, scale, offset, 4, "#FFFFFFFF", "Status bar icon for new messages: the mark.")
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        "</adaptive-icon>\n"
    )
    anydpi = RES / "mipmap-anydpi-v26"
    anydpi.mkdir(exist_ok=True)
    for name in ("ic_launcher", "ic_launcher_round"):
        (anydpi / f"{name}.xml").write_text(adaptive)
    (RES / "values" / "ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
        f'    <color name="ic_launcher_background">{INK}</color>\n</resources>\n'
    )
    # Bitmaps for anything that can't draw the adaptive icon.
    scale, offset = centered(192, 0.64)
    square = png(mark_svg(192, scale, offset, ICON_STROKE, PAPER, background=(0, 192), radius=36), 192)
    round_svg = mark_svg(192, scale, offset, ICON_STROKE, PAPER, background=(0, 192), radius=96)
    round_icon = png(round_svg, 192)
    for folder, pixels in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        square.resize((pixels, pixels), Image.LANCZOS).save(RES / f"mipmap-{folder}" / "ic_launcher.png")
        round_icon.resize((pixels, pixels), Image.LANCZOS).save(RES / f"mipmap-{folder}" / "ic_launcher_round.png")


if __name__ == "__main__":
    iphone()
    mac()
    android()
    print("icons written")
