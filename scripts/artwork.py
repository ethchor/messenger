def load_scene(file):
    svg = SVG.parse(str(file))
    lines = []
    for element in svg.elements():
        if not isinstance(element, Shape) or isinstance(element, SVG):
            continue
        values = element.values
        classes = (values.get("class") or "").split()
        filled = (values.get("fill") or "none").strip() != "none"
        kind = "K" if "knockout" in classes else ("F" if filled else "S")
        width = float(element.stroke_width) if element.stroke_width is not None else 0.0
        if isinstance(element, Circle) and kind != "K":
            x, y, r = (f"{v:.1f}".rstrip("0").rstrip(".") for v in (element.cx, element.cy, element.rx))
            lines.append(f"D {x} {y} {r}" if kind == "F" else f"O {number(width)} {x} {y} {r}")
            continue
        data = re.sub(r"-?\d+\.\d+", lambda m: f"{float(m.group()):.1f}".rstrip("0").rstrip("."), path_data(element))
        if data:
            lines.append(f"{kind} {number(width)} {data}")
    return {"name": file.stem, "width": svg.viewbox.width, "height": svg.viewbox.height, "text": "\n".join(lines) + "\n"}


