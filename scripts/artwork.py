#!/usr/bin/env python3
"""Turns the line drawings in design/artwork into code for both apps.

    scripts/artwork.py              # write Artwork.swift and Artwork.kt
    scripts/artwork.py --check      # fail if they're out of date (CI)
    scripts/artwork.py --preview D  # render every drawing to D/*.png

Each drawing is an SVG of plain strokes in one colour, like a pen line:
- elements are stroked, with their own stroke-width or the root's;
- fill="currentColor" fills a shape with the ink (eyes, dots), and strokes
  it too unless it says stroke="none";
- class="knockout" paints a shape with the paper colour, then strokes it, to
  hide the lines behind it;
- stroke-dasharray makes a dashed line.

Shapes are flattened to absolute M, L, C and Z commands, so the apps only
parse those. Needs `pip install svgelements` (and cairosvg for --preview).
"""

import argparse
import pathlib
import sys

from svgelements import (
    SVG,
    Arc,
    Close,
    CubicBezier,
    Line,
    Move,
    Path,
    QuadraticBezier,
    Shape,
)

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "artwork"
SWIFT = ROOT / "apple" / "Messenger" / "Views" / "Artwork.swift"
KOTLIN = ROOT / "android" / "app" / "src" / "main" / "java" / "com" / "qwantarc" / "messenger" / "ui" / "Artwork.kt"

HEADER = "Generated by scripts/artwork.py from design/artwork. Don't edit; change the SVGs and run the script."


def number(value):
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def path_data(shape):
    path = Path(shape)
    path.approximate_arcs_with_cubics()
    out = []
    for segment in path:
        if isinstance(segment, Move):
            out.append(f"M{number(segment.end.x)} {number(segment.end.y)}")
        elif isinstance(segment, Close):
            out.append("Z")
        elif isinstance(segment, Line):
            out.append(f"L{number(segment.end.x)} {number(segment.end.y)}")
        elif isinstance(segment, QuadraticBezier):
            start, control, end = segment.start, segment.control, segment.end
            c1x = start.x + 2 / 3 * (control.x - start.x)
            c1y = start.y + 2 / 3 * (control.y - start.y)
            c2x = end.x + 2 / 3 * (control.x - end.x)
            c2y = end.y + 2 / 3 * (control.y - end.y)
            out.append(f"C{number(c1x)} {number(c1y)} {number(c2x)} {number(c2y)} {number(end.x)} {number(end.y)}")
        elif isinstance(segment, CubicBezier):
            c1, c2, end = segment.control1, segment.control2, segment.end
            out.append(f"C{number(c1.x)} {number(c1.y)} {number(c2.x)} {number(c2.y)} {number(end.x)} {number(end.y)}")
        elif isinstance(segment, Arc):
            raise ValueError("arc left after approximation")
    return " ".join(out)


def load(file):
    svg = SVG.parse(str(file))
    width, height = svg.viewbox.width, svg.viewbox.height
    stroke_width = float(svg.values.get("stroke-width", 2))
    strokes = []
    for element in svg.elements():
        if not isinstance(element, Shape) or isinstance(element, SVG):
            continue
        values = element.values
        classes = (values.get("class") or "").split()
        # svgelements reports currentColor as a colour name; "none" is the only no-fill.
        filled = (values.get("fill") or "none").strip() != "none"
        stroked = (values.get("stroke") or "none").strip() != "none"
        if "knockout" in classes:
            kind = "knockout"
        elif filled:
            kind = "fill"
        else:
            kind = "stroke"
        line = float(element.stroke_width) if stroked and element.stroke_width is not None else 0.0
        dash = values.get("stroke-dasharray")
        dashes = [float(part) for part in dash.replace(",", " ").split()] if dash and dash != "none" else []
        data = path_data(element)
        if data:
            strokes.append((kind, data, line, dashes))
    return {"name": file.stem, "width": width, "height": height, "stroke": stroke_width, "strokes": strokes}


def camel(name, upper):
    parts = name.replace("_", "-").split("-")
    text = "".join(part[:1].upper() + part[1:] for part in parts)
    return text if upper else text[:1].lower() + text[1:]


def swift(drawings):
    lines = [f"// {HEADER}", "", "import CoreGraphics", "", "enum Artwork: String, CaseIterable {"]
    for d in drawings:
        lines.append(f'    case {camel(d["name"], False)} = "{d["name"]}"')
    lines += ["", "    var size: CGSize {", "        switch self {"]
    for d in drawings:
        lines.append(f'        case .{camel(d["name"], False)}: CGSize(width: {number(d["width"])}, height: {number(d["height"])})')
    lines += ["        }", "    }", "", "    /// Line width, in the drawing's own units.", "    var lineWidth: CGFloat {", "        switch self {"]
    for d in drawings:
        lines.append(f'        case .{camel(d["name"], False)}: {number(d["stroke"])}')
    lines += ["        }", "    }", "", "    var strokes: [ArtworkStroke] {", "        switch self {"]
    for d in drawings:
        lines.append(f'        case .{camel(d["name"], False)}:')
        lines.append("            [")
        for kind, data, line, dashes in d["strokes"]:
            dash = ", ".join(number(x) for x in dashes)
            lines.append(f'                ArtworkStroke(.{kind}, "{data}", width: {number(line)}, dash: [{dash}]),')
        lines.append("            ]")
    lines += ["        }", "    }", "}", ""]
    return "\n".join(lines)


def kotlin(drawings):
    kinds = {"stroke": "Stroke", "fill": "Fill", "knockout": "Knockout"}
    entries = []
    for d in drawings:
        strokes = [
            f'            ArtworkStroke(StrokeKind.{kinds[kind]}, "{data}", {number(line)}f, listOf({", ".join(number(x) + "f" for x in dashes)})),'
            for kind, data, line, dashes in d["strokes"]
        ]
        entries.append(
            "\n".join(
                [
                    f'    {camel(d["name"], True)}(',
                    f'        "{d["name"]}", {number(d["width"])}f, {number(d["height"])}f, {number(d["stroke"])}f,',
                    "        listOf(",
                    *strokes,
                    "        ),",
                    "    )",
                ]
            )
        )
    lines = [
        f"// {HEADER}",
        "",
        "package com.qwantarc.messenger.ui",
        "",
        "enum class Artwork(val id: String, val width: Float, val height: Float, val lineWidth: Float, val strokes: List<ArtworkStroke>) {",
        ",\n".join(entries) + ";",
        "",
        "    companion object {",
        "        fun byId(id: String): Artwork? = entries.firstOrNull { it.id == id }",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def preview(drawings, directory):
    import cairosvg

    directory.mkdir(parents=True, exist_ok=True)
    for d in drawings:
        body = []
        for kind, data, line, dashes in d["strokes"]:
            dash = f' stroke-dasharray="{" ".join(number(x) for x in dashes)}"' if dashes else ""
            stroke = f'stroke-width="{number(line)}"' if line > 0 else 'stroke="none"'
            fill = {"fill": "#1d2b4f", "knockout": "#ffffff"}.get(kind, "none")
            body.append(f'<path d="{data}" fill="{fill}" {stroke}{dash}/>')
        svg = (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {number(d["width"])} {number(d["height"])}" '
            f'width="{int(d["width"] * 4)}" height="{int(d["height"] * 4)}" stroke="#1d2b4f" '
            f'stroke-width="{number(d["stroke"])}" stroke-linecap="round" stroke-linejoin="round">'
            f'<rect width="100%" height="100%" fill="#ffffff" stroke="none"/>{"".join(body)}</svg>'
        )
        cairosvg.svg2png(bytestring=svg.encode(), write_to=str(directory / f'{d["name"]}.png'))
    print(f"wrote {len(drawings)} previews to {directory}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    parser.add_argument("--preview", type=pathlib.Path, help="render the drawings to PNGs in this folder")
    args = parser.parse_args()

    drawings = [load(file) for file in sorted(SOURCE.glob("*.svg"))]
    if args.preview:
        preview(drawings, args.preview)
        return
    outputs = {SWIFT: swift(drawings), KOTLIN: kotlin(drawings)}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if args.check:
        if stale:
            print("Out of date, run scripts/artwork.py:", *(str(p.relative_to(ROOT)) for p in stale), sep="\n  ")
            sys.exit(1)
        return
    for path in stale:
        path.write_text(outputs[path])
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
