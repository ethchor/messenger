#!/usr/bin/env python3
"""Turns the drawings in design/artwork, design/avatars, design/illustrations
and design/wallpapers into code for both apps.

    scripts/artwork.py              # write Artwork, Avatars, Illustrations and Wallpapers .swift and .kt
    scripts/artwork.py --check      # fail if they're out of date (CI)
    scripts/artwork.py --preview D  # render every drawing and illustration to D/*.png

Each line drawing is an SVG of plain strokes in one colour, like a pen line:
- elements are stroked, with their own stroke-width or the root's;
- fill="currentColor" fills a shape with the ink (eyes, dots), and strokes
  it too unless it says stroke="none";
- class="knockout" paints a shape with the paper colour, then strokes it, to
  hide the lines behind it;
- stroke-dasharray makes a dashed line.

The avatars are in colour: each element keeps its own fill and stroke, and the
apps draw them in order on a circle of the person's ink, clipped round. They're
offered in the order of design/avatars/order.txt.

The wallpapers are line drawings like design/artwork: seamless square tiles,
offered in the order of design/wallpapers/order.txt, which also names them.

The scenes in design/wallpapers/scenes (drawn by scripts/wallpapers.py) are
whole-screen line drawings. They're too big for code, so each becomes a text
file the apps bundle (scene-<name>.txt in the Apple resources and the Android
assets), one shape per line: S, K or F for stroke, knockout or fill, the line
width, then the path; D (a dot) or O (a ring, with its line width) for
circles, with the centre and radius. Coordinates keep one decimal.

The illustrations are in colour too, with dashed lines allowed. The shape with
class="backdrop" is painted in the pastel of the person's ink instead of its
own fill.

Shapes are flattened to absolute M, L, C and Z commands, so the apps only
parse those. Needs `pip install svgelements` (and cairosvg for --preview).
"""

