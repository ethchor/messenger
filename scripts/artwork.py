def number(value):
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def path_data(shape):
    path = abs(Path(shape))  # with the element's transform applied
    path.approximate_arcs_with_cubics()
    out = []
    for segment in path:
        if isinstance(segment, Move):
            out.append(f"M{number(segment.end.x)} {number(segment.end.y)}")
        elif isinstance(segment, Close):
            out.append("Z")
        elif isinstance(segment, Line):
            out.append(f"L{number(segment.end.x)} {number(segment.end.y)}")
        elif isinstance(segment, QuadraticBezier):
            start, control, end = segment.start, segment.control, segment.end
            c1x = start.x + 2 / 3 * (control.x - start.x)
            c1y = start.y + 2 / 3 * (control.y - start.y)
            c2x = end.x + 2 / 3 * (control.x - end.x)
            c2y = end.y + 2 / 3 * (control.y - end.y)
            out.append(f"C{number(c1x)} {number(c1y)} {number(c2x)} {number(c2y)} {number(end.x)} {number(end.y)}")
        elif isinstance(segment, CubicBezier):
            c1, c2, end = segment.control1, segment.control2, segment.end
            out.append(f"C{number(c1.x)} {number(c1.y)} {number(c2.x)} {number(c2.y)} {number(end.x)} {number(end.y)}")
        elif isinstance(segment, Arc):
            raise ValueError("arc left after approximation")
    return " ".join(out)


def load(file):
    svg = SVG.parse(str(file))
    width, height = svg.viewbox.width, svg.viewbox.height
    stroke_width = float(svg.values.get("stroke-width", 2))
    strokes = []
    for element in svg.elements():
        if not isinstance(element, Shape) or isinstance(element, SVG):
            continue
        values = element.values
        classes = (values.get("class") or "").split()
        # svgelements reports currentColor as a colour name; "none" is the only no-fill.
        filled = (values.get("fill") or "none").strip() != "none"
        stroked = (values.get("stroke") or "none").strip() != "none"
        if "knockout" in classes:
            kind = "knockout"
        elif filled:
            kind = "fill"
        else:
            kind = "stroke"
        line = float(element.stroke_width) if stroked and element.stroke_width is not None else 0.0
        dashes = dash_array(values)
        data = path_data(element)
        if data:
            strokes.append((kind, data, line, dashes))
    return {"name": file.stem, "width": width, "height": height, "stroke": stroke_width, "strokes": strokes}


def paint(value):
    """An SVG paint as 0xRRGGBB, or None for none."""
    if value is None or value.value is None:
        return None
    return int(value.hexrgb[1:], 16)


def load_avatar(file):
    svg = SVG.parse(str(file))
    title = ET.parse(file).getroot().findtext("{http://www.w3.org/2000/svg}title") or file.stem.title()
    shapes = []
    for element in svg.elements():
        if not isinstance(element, Shape) or isinstance(element, SVG):
            continue
        fill, stroke = paint(element.fill), paint(element.stroke)
        width = float(element.stroke_width) if stroke is not None and element.stroke_width else 0.0
        data = path_data(element)
        if data and (fill is not None or width > 0):
            shapes.append((data, fill, stroke if width > 0 else None, width))
    return {"name": file.stem, "title": title.strip(), "shapes": shapes}


def load_avatars():
    order = [line.strip() for line in (AVATARS / "order.txt").read_text().splitlines()]
    order = [name for name in order if name and not name.startswith("#")]
    files = {file.stem: file for file in AVATARS.glob("*.svg")}
    missing = set(files) - set(order)
    unknown = set(order) - set(files)
    if missing or unknown:
        sys.exit(f"design/avatars/order.txt: add {sorted(missing)}, remove {sorted(unknown)}")
    return [load_avatar(files[name]) for name in order]


def dash_array(values):
    dash = values.get("stroke-dasharray")
    return [float(part) for part in dash.replace(",", " ").split()] if dash and dash != "none" else []


def load_illustration(file):
    svg = SVG.parse(str(file))
    shapes = []
    for element in svg.elements():
        if not isinstance(element, Shape) or isinstance(element, SVG):
            continue
        backdrop = "backdrop" in (element.values.get("class") or "").split()
        fill, stroke = paint(element.fill), paint(element.stroke)
        width = float(element.stroke_width) if stroke is not None and element.stroke_width else 0.0
        data = path_data(element)
        if data and (fill is not None or width > 0):
            shapes.append((data, fill, stroke if width > 0 else None, width, dash_array(element.values), backdrop))
    if sum(shape[5] for shape in shapes) > 1:
        sys.exit(f"{file.relative_to(ROOT)}: only one shape can be the backdrop")
    return {"name": file.stem, "width": svg.viewbox.width, "height": svg.viewbox.height, "shapes": shapes}


