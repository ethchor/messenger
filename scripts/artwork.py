def preview(drawings, illustrations, directory):
    import cairosvg

    directory.mkdir(parents=True, exist_ok=True)
    for d in drawings:
        body = []
        for kind, data, line, dashes in d["strokes"]:
            dash = f' stroke-dasharray="{" ".join(number(x) for x in dashes)}"' if dashes else ""
            stroke = f'stroke-width="{number(line)}"' if line > 0 else 'stroke="none"'
            fill = {"fill": "#1d2b4f", "knockout": "#ffffff"}.get(kind, "none")
            body.append(f'<path d="{data}" fill="{fill}" {stroke}{dash}/>')
        svg = (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {number(d["width"])} {number(d["height"])}" '
            f'width="{int(d["width"] * 4)}" height="{int(d["height"] * 4)}" stroke="#1d2b4f" '
            f'stroke-width="{number(d["stroke"])}" stroke-linecap="round" stroke-linejoin="round">'
            f'<rect width="100%" height="100%" fill="#ffffff" stroke="none"/>{"".join(body)}</svg>'
        )
        cairosvg.svg2png(bytestring=svg.encode(), write_to=str(directory / f'{d["name"]}.png'))
    for d in illustrations:
        body = []
        for data, fill, stroke, width, dashes, _ in d["shapes"]:
            dash = f' stroke-dasharray="{" ".join(number(x) for x in dashes)}"' if dashes else ""
            fill = f"#{fill:06X}" if fill is not None else "none"
            stroke = f'stroke="#{stroke:06X}" stroke-width="{number(width)}"' if stroke is not None else 'stroke="none"'
            body.append(f'<path d="{data}" fill="{fill}" {stroke}{dash}/>')
        svg = (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {number(d["width"])} {number(d["height"])}" '
            f'width="{int(d["width"] * 4)}" height="{int(d["height"] * 4)}" stroke-linecap="round" stroke-linejoin="round">'
            f'<rect width="100%" height="100%" fill="#ffffff"/>{"".join(body)}</svg>'
        )
        cairosvg.svg2png(bytestring=svg.encode(), write_to=str(directory / f'illustration-{d["name"]}.png'))
    print(f"wrote {len(drawings) + len(illustrations)} previews to {directory}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if the generated files are out of date")
    parser.add_argument("--preview", type=pathlib.Path, help="render the drawings to PNGs in this folder")
    args = parser.parse_args()

    drawings = [load(file) for file in sorted(SOURCE.glob("*.svg"))]
    illustrations = [load_illustration(file) for file in sorted(ILLUSTRATIONS.glob("*.svg"))]
    if args.preview:
        preview(drawings, illustrations, args.preview)
        return
    avatars = load_avatars()
    wallpapers = load_wallpapers()
    scenes = load_scenes()
    outputs = {
        SWIFT: swift(drawings),
        KOTLIN: kotlin(drawings),
        AVATARS_SWIFT: avatars_swift(avatars),
        AVATARS_KOTLIN: avatars_kotlin(avatars),
        ILLUSTRATIONS_SWIFT: illustrations_swift(illustrations),
        ILLUSTRATIONS_KOTLIN: illustrations_kotlin(illustrations),
        WALLPAPERS_SWIFT: wallpapers_swift(wallpapers),
        WALLPAPERS_KOTLIN: wallpapers_kotlin(wallpapers),
        SCENES_SWIFT: scenes_swift(scenes),
        SCENES_KOTLIN: scenes_kotlin(scenes),
    }
    for scene in scenes:
        outputs[SCENE_RESOURCES / f"scene-{scene['name']}.txt"] = scene["text"]
        outputs[SCENE_ASSETS / f"scene-{scene['name']}.txt"] = scene["text"]
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if args.check:
        if stale:
            print("Out of date, run scripts/artwork.py:", *(str(p.relative_to(ROOT)) for p in stale), sep="\n  ")
            sys.exit(1)
        return
    for path in stale:
        path.write_text(outputs[path])
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
